	[Fact]
	public void RoundedAssemblyKeepsIdentityAndUsesLongitudinalCapsules()
	{
		var inputs = BoardCollisionInputs.CreateRoundParts( new Vector3( .8f, .22f, .025f ),
			.00833125039935112f, .06412500143051147f, .031f, 50 );
		var bodies = Enumerable.Range( 0, 7 ).Select( i => new DynamicBody
		{
			Rotation = Quaternion.Identity, Position = new Vector3( i, 2, 3 ), InverseMass = 1,
			WorldInverseInertia = Matrix4x4.Identity
		} ).ToArray();
		inputs.Update( bodies, 3, 17, .6f, .4f, .1f );
		Assert.Equal( 4, inputs.Bodies.Span[ 0 ].ShapeKind );
		for ( var i = 1; i < 7; ++i )
		{
			var input = inputs.Bodies.Span[ i ];
			Assert.Equal( i < 3 ? 2 : 1, input.ShapeKind );
			Assert.Equal( (uint)i + 1, input.BodyIdentity );
			Assert.Equal( (uint)i + 50, input.ShapeIdentity );
			Assert.Equal( W( i < 3 ? .00833125039935112f : .031f ), input.Shape.Span[ 20 ] );
			Assert.Equal( 4u, input.BodyState.Span[ 35 ] );
			Assert.Equal( W( i ), input.Transform.Span[ 12 ] );
			if ( i >= 3 ) continue;
			Assert.Equal( W( .06412500143051147f ), input.Shape.Span[ 17 ] );
			Assert.Equal( new uint[] { W( 1 ), 0, 0 }, input.Shape.Span.Slice( 8, 3 ).ToArray() );
			var descriptor = new uint[ 44 ];
			Assert.True( CollisionShapeConstruction.TryConstruct( input.ShapeKind, input.Shape.Span,
				descriptor, input.Transform.Span, input.ShapeIdentity ) );
			Assert.Equal( new uint[] { W( 1 ), 0, 0 }, descriptor[ 16..19 ] );
		}
	}

