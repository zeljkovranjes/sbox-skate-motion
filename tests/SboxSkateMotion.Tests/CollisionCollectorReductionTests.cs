	[Theory]
	[InlineData( 51, 3264 )]
	[InlineData( 2, 127 )]
	[InlineData( -1, 3200 )]
	public void InvalidCountLeavesRecordsAndCountUntouched( int suppliedCount, int words )
	{
		var count = unchecked((uint)suppliedCount);
		var records = Enumerable.Repeat( 0x12345678u, words ).ToArray();
		Assert.Throws<ArgumentOutOfRangeException>( () => CollisionCollectorReduction.Reduce( records, ref count ) );
		Assert.Equal( unchecked((uint)suppliedCount), count );
		Assert.All( records, word => Assert.Equal( 0x12345678u, word ) );
	}

	[Fact]
	public void EmptyInputHasNoSideEffects()
	{
		var count = 0u;
		CollisionCollectorReduction.Reduce( Span<uint>.Empty, ref count );
		Assert.Equal( 0u, count );
	}

	[Fact]
	public void GroupsOfFourKeepEvenCoincidentContacts()
	{
		var records = new uint[ 4 * 64 ];
		for ( var i = 0; i < 4; ++i )
		{
			records[ i * 64 + 3 ] = 1;
			records[ i * 64 + 7 ] = 2;
			records[ i * 64 + 10 ] = 0x3f800000u;
			records[ i * 64 + 63 ] = (uint)i;
		}
		var before = records.AsSpan().ToArray();
		var count = 4u;
		CollisionCollectorReduction.Reduce( records, ref count );
		Assert.Equal( 4u, count );
		Assert.Equal( before, records );
	}
