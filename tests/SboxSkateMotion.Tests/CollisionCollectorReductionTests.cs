	[Theory]
	[MemberData( nameof( GeometryCases ) )]
	public void GeometricGroupsKeepSelectedRecordsInOriginalOrder( uint[][] geometry, int[] selected )
	{
		var records = new uint[ (geometry.Length + 2) * 64 ];
		for ( var i = 0; i < records.Length; ++i )
			records[ i ] = 0x5a000000u | (uint)i;
		for ( var i = 0; i < geometry.Length; ++i )
			geometry[ i ].CopyTo( records, i * 64 );
		var before = records.AsSpan().ToArray();
		var count = (uint)geometry.Length;
		CollisionCollectorReduction.Reduce( records, ref count );
		Assert.Equal( (uint)selected.Length, count );
		for ( var i = 0; i < selected.Length; ++i )
			Assert.Equal( before.Skip( selected[ i ] * 64 ).Take( 64 ), records.Skip( i * 64 ).Take( 64 ) );
		Assert.Equal( before.Skip( selected.Length * 64 ), records.Skip( selected.Length * 64 ) );
	}

