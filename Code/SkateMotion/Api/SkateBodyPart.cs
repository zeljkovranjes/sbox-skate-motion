namespace SkateMotion;

/// <summary>Physical parts in the articulated skateboard.</summary>
public enum SkateBodyPart
{
	/// <summary>Deck and attached rider load.</summary>
	Deck,
	/// <summary>Front steering truck.</summary>
	FrontTruck,
	/// <summary>Rear steering truck.</summary>
	RearTruck,
	/// <summary>Front wheel on the board's left side.</summary>
	FrontLeftWheel,
	/// <summary>Front wheel on the board's right side.</summary>
	FrontRightWheel,
	/// <summary>Rear wheel on the board's left side.</summary>
	RearLeftWheel,
	/// <summary>Rear wheel on the board's right side.</summary>
	RearRightWheel
}
